// health-care/backend/src/models/Lead.js
//
// Phase 4.2 — CRM lead pipeline (Workstream A of the Phase 4.0 growth plan).
//
// AUTHORITY: docs/growth/crm-field-contract.md is the authoritative business
// field contract. The business field names below intentionally use the
// contract's snake_case so the stored document maps 1:1 onto the CRM
// spreadsheet/Notion schema; the rest of this backend keeps camelCase.
//
// System-of-record boundaries (never violated here):
//   • Customers  → models/User.js        (a lead only *references* a user)
//   • Quotations → models/Quote.js       (a lead only *references* a quote;
//                                         quotations are never duplicated in CRM)
//   • Orders     → models/Order.js       (untouched)
//   • Behavior   → GA4 + models/MarketingEvent.js (funnel activity, NOT leads)
//
// No PII beyond published business contact information is stored. Free-form
// notes are sanitised by the controller before they reach this model.

const mongoose = require('mongoose');

// ── Enums — taken verbatim from docs/growth/crm-field-contract.md ───────────
const LEAD_STATUSES = ['new', 'verified', 'contacted', 'qualified', 'rfq', 'quoted', 'won', 'lost', 'dormant'];
const LEAD_SOURCES = ['organic', 'google_ads', 'meta', 'whatsapp_direct', 'outbound', 'referral', 'event', 'existing_customer'];
const ORG_TYPES = ['hospital', 'clinic', 'diagnostic_centre', 'laboratory', 'pharmacy', 'institution', 'healthcare_professional', 'other'];
const RFQ_STATUSES = ['none', 'requested', 'quoted', 'negotiating', 'won', 'lost'];
const CUSTOMER_STATUSES = ['prospect', 'first_order', 'repeat', 'standing_order'];
const LEAD_QUALITIES = ['unrated', 'cold', 'warm', 'hot'];

// Only the four allowlisted campaign keys ever persist (Phase 4.1 convention).
const UTM_KEYS = ['utm_source', 'utm_medium', 'utm_campaign', 'utm_content'];

// ── Field validation patterns (Phase 4.2-B) ────────────────────────────────
// phone/email reuse the exact conventions already approved in the WIP
// crmController — no third-party validation dependency introduced.
const PHONE_PATTERN = /^[0-9+\-().\s]{6,20}$/; // F-04/4.2A approved phone shape
const EMAIL_PATTERN = /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/; // controller EMAIL_REGEX
const WEBSITE_PATTERN = /^https?:\/\/\S+$/i; // must use http:// or https://
const LEAD_ID_PATTERN = /^LD-\d{4}-\d{4}$/; // LD-YYYY-NNNN

// Client-supplied touch timestamps must be plausible. The 4.2-C API phase
// enforces trusted server time on writes; the schema rejects impossible
// (future) values here without rewriting attribution architecture.
const notFutureTimestamp = {
  validator: (v) => !v || v.getTime() <= Date.now() + 60000, // 60s clock-skew allowance
  message: '{PATH} cannot be a future timestamp',
};

// Deterministic pipeline. Forward-only with explicit terminal/re-open edges so
// invalid jumps (e.g. new → won) are rejected rather than silently stored.
const TRANSITIONS = {
  new: ['verified', 'contacted', 'lost'],
  verified: ['contacted', 'qualified', 'lost'],
  contacted: ['qualified', 'rfq', 'lost'],
  qualified: ['rfq', 'quoted', 'lost'],
  rfq: ['quoted', 'lost'],
  quoted: ['won', 'lost'],
  won: [],
  lost: ['dormant'],
  dormant: ['contacted', 'lost'],
};

const noteSchema = new mongoose.Schema(
  {
    text: {
      type: String,
      required: true,
      maxlength: 2000,
      // Defence in depth (Phase 4.2A O-5): raw markup never reaches storage,
      // even if a caller bypasses the controller-level sanitizeNote() helper.
      validate: {
        validator: (v) => !/<\/?[a-zA-Z!?]|<>/.test(v),
        message: 'Note must not contain HTML markup',
      },
    },
    at: { type: Date, default: Date.now },
    by: { type: String, default: 'admin' }, // role label only, never a person's PII
  },
  { _id: true }
);

const relatedQuoteSchema = new mongoose.Schema(
  {
    quote: { type: mongoose.Schema.Types.ObjectId, ref: 'Quote' },
    quote_number: { type: String, required: true },
    linked_at: { type: Date, default: Date.now },
  },
  { _id: false }
);

const leadSchema = new mongoose.Schema(
  {
    // Stable human-facing identifier (LD-2026-0001), generated by the
    // collision-safe pre('save') hook below (same pattern as Quote numbers).
    // NOT schema-`required`: mongoose validates BEFORE pre('save') hooks run
    // (verified empirically), so requiredness is enforced by the generator +
    // the unique index — mirroring Quote.quoteId/quoteNumber. Predictable
    // sequence values: never treat as a security token.
    lead_id: { type: String, unique: true, index: true, match: LEAD_ID_PATTERN },

    // ── Organisation ────────────────────────────────────────────────────────
    organization: { type: String, required: true, trim: true, minlength: 2, maxlength: 200 },
    organization_type: { type: String, enum: ORG_TYPES, required: true },
    city: { type: String, trim: true, maxlength: 120 },
    district: { type: String, required: true, trim: true, maxlength: 120 },
    division: { type: String, required: true, trim: true, maxlength: 120 },

    // ── Contact (published business information only) ───────────────────────
    contact_name: { type: String, trim: true, maxlength: 160 },
    contact_role: { type: String, trim: true, maxlength: 120 },
    phone: { type: String, required: true, trim: true, maxlength: 20, match: PHONE_PATTERN },
    email: {
      type: String,
      trim: true,
      lowercase: true, // normalised to lowercase on write
      maxlength: 200,
      validate: {
        validator: (v) => !v || EMAIL_PATTERN.test(v), // same shape rule as the WIP controller
        message: 'Invalid email address',
      },
    },
    website: {
      type: String,
      trim: true,
      maxlength: 300,
      validate: {
        validator: (v) => !v || WEBSITE_PATTERN.test(v),
        message: 'website must use http:// or https://',
      },
    },
    facebook_url: { type: String, trim: true, maxlength: 300 },
    linkedin_url: { type: String, trim: true, maxlength: 300 },

    // ── Commercial intent ───────────────────────────────────────────────────
    likely_product_category: { type: String, trim: true, maxlength: 160 },

    // ── Attribution (first touch, four allowlisted UTM keys only) ───────────
    source: { type: String, enum: LEAD_SOURCES, required: true },
    medium: { type: String, trim: true, maxlength: 64 },
    campaign: { type: String, trim: true, maxlength: 64 },
    content: { type: String, trim: true, maxlength: 64 },
    landing_page: { type: String, trim: true, maxlength: 300 },
    first_touch_at: { type: Date, default: Date.now, validate: notFutureTimestamp },
    last_touch_at: { type: Date, default: Date.now, validate: notFutureTimestamp },
    first_contact_at: { type: Date },

    // ── Pipeline state ──────────────────────────────────────────────────────
    status: { type: String, enum: LEAD_STATUSES, default: 'new', required: true, index: true },
    lead_quality: { type: String, enum: LEAD_QUALITIES, default: 'unrated' },
    assigned_to: { type: String, trim: true, maxlength: 120, default: null },
    notes: {
      type: [noteSchema],
      default: [],
      validate: {
        validator: (v) => v.length <= 100, // hard cap (contract follow-up section)
        message: 'A lead may hold at most 100 notes',
      },
    },

    // Quote-system references (never a copy of the quotation itself)
    rfq_status: { type: String, enum: RFQ_STATUSES, default: 'none' },
    related_quotes: { type: [relatedQuoteSchema], default: [] },

    // Optional links to the authoritative systems
    customer: { type: mongoose.Schema.Types.ObjectId, ref: 'User', default: null },
    customer_status: { type: String, enum: CUSTOMER_STATUSES, default: 'prospect' },

    // Follow-up discipline (contract rule: no status advance without a next action)
    last_contact: { type: Date },
    next_action: { type: String, trim: true, maxlength: 300 },
    next_action_date: { type: Date },
  },
  {
    timestamps: { createdAt: 'created_at', updatedAt: 'updated_at' },
    minimize: false,
  }
);

leadSchema.index({ status: 1, created_at: -1 });
leadSchema.index({ source: 1, created_at: -1 });
leadSchema.index({ district: 1, division: 1 });
leadSchema.index({ organization_type: 1 });

// Collision-safe human lead id: LD-<year>-<4 digit sequence>
leadSchema.pre('save', async function (next) {
  try {
    if (this.lead_id) {
      return next();
    }
    const year = new Date().getFullYear();
    const prefix = `LD-${year}-`;
    const last = await this.constructor
      .findOne({ lead_id: { $regex: `^${prefix}` } })
      .sort({ lead_id: -1 })
      .select('lead_id')
      .lean();
    let seq = 1;
    if (last && last.lead_id) {
      const m = last.lead_id.match(/(\d+)$/);
      seq = m ? parseInt(m[1], 10) + 1 : 1;
    }
    for (let i = 0; i < 5; i++) {
      const candidate = `${prefix}${String(seq).padStart(4, '0')}`;
      const exists = await this.constructor.findOne({ lead_id: candidate }).select('_id').lean();
      if (!exists) {
        this.lead_id = candidate; return next(); 
      }
      seq += 1;
    }
    return next(new Error('Failed to generate a unique lead id'));
  } catch (err) {
    return next(err);
  }
});

// ── Pure helpers (no I/O, unit-testable without a database) ────────────────

/**
 * Derive `lead_source` from the Phase 4.1 first-touch UTM tuple.
 * Mapping rule is defined in docs/growth/crm-field-contract.md (Enums → lead_source).
 */
function deriveLeadSource(attribution = {}, options = {}) {
  const src = String(attribution.utm_source || '').toLowerCase();
  const med = String(attribution.utm_medium || '').toLowerCase();
  if (options.isRepeatCustomer) {
    return 'existing_customer';
  }
  if (options.whatsappDirect) {
    return 'whatsapp_direct';
  }
  if (src === 'google' && med === 'cpc') {
    return 'google_ads';
  }
  if (src === 'facebook' || src === 'instagram') {
    return 'meta';
  }
  if (src) {
    return 'referral';
  }
  if (med) {
    return 'outbound';
  }
  if (options.referralFromSite) {
    return 'referral';
  }
  if (options.eventTraffic) {
    return 'event';
  }
  return 'organic';
}

/** Keep only the four allowlisted UTM keys, trimmed + capped at 64 chars. */
function sanitizeAttribution(raw = {}) {
  const out = {};
  for (const key of UTM_KEYS) {
    const val = raw[key];
    if (typeof val === 'string') {
      const clean = val.trim().slice(0, 64);
      if (clean) {
        out[key] = clean;
      }
    }
  }
  return out;
}

/**
 * Strip control chars/markup from a note and cap its length. (Phase 4.2A O-5)
 *
 * Markup-only input must be REJECTED (returns ''), not silently converted into
 * non-empty text: '<b></b>', '<script></script>', '<>' and whitespace-only all
 * collapse to ''. Normal business text ("Need quotation for 3 ECG machines")
 * survives byte-for-byte. script/style blocks are removed WITH their content;
 * every other tag (closed or unterminated) is dropped. No HTML rendering ever.
 */
function sanitizeNote(text) {
  if (typeof text !== 'string') {
    return '';
  }
  // eslint-disable-next-line no-control-regex -- deliberate: note sanitisation MUST strip control chars
  let clean = text.replace(/[\u0000-\u001F\u007F]/g, ' ');
  if (/<\/?[a-zA-Z!?]|<>/.test(clean)) {
    clean = clean
      .replace(/<script[\s\S]*?(?:<\/script>|$)/gi, ' ')
      .replace(/<style[\s\S]*?(?:<\/style>|$)/gi, ' ')
      .replace(/<[^>]*>?/g, ' ');
  }
  return clean.replace(/\s+/g, ' ').trim().slice(0, 2000);
}

/** Deterministic status transition check (same-state is always allowed). */
function canTransition(from, to) {
  if (!from || !to) {
    return false;
  }
  if (from === to) {
    return true;
  }
  const allowed = TRANSITIONS[from];
  return Array.isArray(allowed) && allowed.includes(to);
}

// ── Application-level duplicate-lead strategy (Phase 4.2A O-3) ─────────────
// DB-unique constraints on organization/phone/email are deliberately ABSENT:
// shared switchboards, multi-branch facilities and repeat opportunities are
// legitimate business reality. Strategy for the upcoming CRM API (4.2-C):
//   1. narrow candidates with buildDuplicateCandidateQuery(),
//   2. confirm with the normalisers / isPotentialDuplicate(),
//   3. surface a non-blocking "possible duplicate" hint —
// NEVER auto-reject a lead, NEVER merge records automatically.

/** Lowercase + collapse internal whitespace + trim (generic text key). */
function normalizeTextKey(value) {
  if (typeof value !== 'string') {
    return '';
  }
  return value.toLowerCase().replace(/\s+/g, ' ').trim();
}

/** Organisation match key (case/spacing-insensitive). */
function normalizeOrgKey(value) {
  return normalizeTextKey(value);
}

/**
 * Digit sequence key for phones: strips separators and the common
 * +880 / 0 country+trunk prefixes so '01712345678', '+8801712345678'
 * and '880-17-12345678' all normalise to the same value.
 */
function normalizePhoneKey(value) {
  if (typeof value !== 'string') {
    return '';
  }
  let digits = value.replace(/\D/g, '');
  if (digits.startsWith('880')) {
    digits = digits.slice(3);
  }
  digits = digits.replace(/^0+/, '');
  return digits;
}

/** Email match key (lowercase + trim — matches the schema's lowercase write). */
function normalizeEmailKey(value) {
  if (typeof value !== 'string') {
    return '';
  }
  return value.toLowerCase().trim();
}

function escapeRegexForDedupe(value) {
  return String(value).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/**
 * Narrow candidate query for future duplicate lookups. Returns a MongoDB
 * $or of format-insensitive clauses (or null when there is nothing to
 * match). Deliberately NOT used to reject writes.
 */
function buildDuplicateCandidateQuery(input = {}) {
  const clauses = [];
  const org = normalizeOrgKey(input.organization);
  if (org) {
    clauses.push({ organization: { $regex: `^${escapeRegexForDedupe(org)}$`, $options: 'i' } });
  }
  const email = normalizeEmailKey(input.email);
  if (email) {
    clauses.push({ email });
  }
  const phoneKey = normalizePhoneKey(input.phone);
  if (phoneKey) {
    const chain = phoneKey.split('').map((ch) => `[\\s\\-\\.()+]*${ch}`).join('');
    clauses.push({ phone: { $regex: `^\\+?[\\s]*(?:880|0)?[\\s\\-\\.()+]*${chain}$` } });
  }
  return clauses.length ? { $or: clauses } : null;
}

/**
 * Confirm whether an existing lead is a *potential* duplicate of a candidate.
 * Signals: same phone key OR same email key OR (same organisation AND same
 * district — a different district means a different branch, not a duplicate).
 */
function isPotentialDuplicate(existing = {}, candidate = {}) {
  const ep = normalizePhoneKey(existing.phone);
  const cp = normalizePhoneKey(candidate.phone);
  if (ep && cp && ep === cp) {
    return true;
  }
  const ee = normalizeEmailKey(existing.email);
  const ce = normalizeEmailKey(candidate.email);
  if (ee && ce && ee === ce) {
    return true;
  }
  const eo = normalizeOrgKey(existing.organization);
  const co = normalizeOrgKey(candidate.organization);
  if (eo && co && eo === co) {
    const ed = normalizeTextKey(existing.district);
    const cd = normalizeTextKey(candidate.district);
    return !ed || !cd || ed === cd;
  }
  return false;
}

