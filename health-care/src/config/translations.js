/**
 * Hook-friendly translation getter
 * @param {string} lang - 'en' | 'bn'
 * @returns {function} t(dotPath) - e.g. t('nav.products')
 */
export function getT(lang) {
  const dict = translations[lang] || translations.en;
  return function t(path) {
    const keys = path.split('.');
    let val = dict;
    for (const k of keys) {
      val = val?.[k];
      if (val === undefined) return path; // fallback to key
    }
    return val;
  };
}

